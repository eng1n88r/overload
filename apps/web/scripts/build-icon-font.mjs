/**
 * Builds the app's icon font from Tabler Icons.
 *
 * Tabler ships 5,193 glyphs in a 452 KB webfont; Overload uses 32 of them. This
 * subsets the font down to just those and writes the matching stylesheet, so
 * the app ships a few KB instead. Both outputs are committed -- @tabler/icons-webfont
 * is only a devDependency, needed to regenerate.
 *
 *   npm run icons -w @overload/web
 *
 * To add an icon: put it in ICONS below, rerun, and use <i class="ti ti-name">.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const here = dirname(fileURLToPath(import.meta.url));
const web = resolve(here, '..');
const root = resolve(web, '../..');

/** Every Tabler glyph the app uses. Keep alphabetical. */
const ICONS = [
  'adjustments', 'apple', 'archive', 'arrow-down', 'arrow-left', 'arrow-up',
  'arrows-maximize', 'barbell', 'calendar-week', 'chart-line', 'check',
  'chevron-down', 'chevron-right', 'color-swatch', 'contrast', 'flame', 'heartbeat', 'hourglass',
  'key', 'layout-dashboard', 'list-check', 'logout', 'moon-stars',
  'pencil', 'player-play', 'plus', 'sparkles', 'stopwatch', 'sun', 'trash',
  'user-circle', 'x',
];

const pkg = resolve(root, 'node_modules/@tabler/icons-webfont/dist');
const css = readFileSync(resolve(pkg, 'tabler-icons.css'), 'utf8');

const codepoints = new Map(
  [...css.matchAll(/\.ti-([\w-]+):before\s*\{\s*content:\s*"\\([0-9a-fA-F]+)"/gs)]
    .map(([, name, hex]) => [name, hex]),
);

const missing = ICONS.filter((n) => !codepoints.has(n));
if (missing.length) throw new Error(`not in Tabler: ${missing.join(', ')}`);

const chars = ICONS.map((n) => String.fromCodePoint(parseInt(codepoints.get(n), 16))).join('');
const source = readFileSync(resolve(pkg, 'fonts/tabler-icons.woff2'));
const subset = await subsetFont(source, chars, { targetFormat: 'woff2' });

const outDir = resolve(web, 'src/assets/icons');
mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, 'overload-icons.woff2'), subset);

const rules = ICONS.map((n) => `.ti-${n}::before { content: '\\${codepoints.get(n)}'; }`).join('\n');
writeFileSync(
  resolve(outDir, 'icons.css'),
  `/* Generated by scripts/build-icon-font.mjs -- do not edit by hand.
   Subset of Tabler Icons (MIT), ${ICONS.length} glyphs. */
@font-face {
  font-family: 'overload-icons';
  src: url('./overload-icons.woff2') format('woff2');
  font-weight: 400;
  font-style: normal;
  font-display: block;
}
.ti {
  font-family: 'overload-icons' !important;
  font-style: normal;
  font-weight: 400 !important;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  display: inline-block;
  vertical-align: -0.125em;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}
${rules}
`,
);

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
console.log(`${ICONS.length} glyphs: ${kb(source.length)} -> ${kb(subset.length)}`);
